import { Info } from 'lucide-react'
import { post } from '../../lib/api'
import { Badge, cx } from '../../components/ui'
import { AiFeedbackGate, BandPill, Notes } from '../feedback'
import type { SpeakingSession } from './recorder'

/** Shows the analysis of one recorded answer: transcript, measurements, rule-based notes and optional AI feedback. */
export function SpeakingResult({ s, onUpdate, allowAi = true }: { s: SpeakingSession; onUpdate: (s: SpeakingSession) => void; allowAi?: boolean }) {
  const m = s.metrics
  if (s.mode === 'read-aloud' && s.feedback.readAloud) {
    const ra = s.feedback.readAloud
    return (
      <div className="space-y-4">
        <div className="card p-5">
          <p className="text-sm font-semibold text-muted">Words recognised</p>
          <p className="mt-1 text-3xl font-extrabold tabular-nums">{ra.percent}% <span className="text-base font-semibold text-muted">({ra.matched}/{ra.total})</span></p>
          <p className="mt-3 text-lg leading-relaxed">
            {ra.words.map((w, i) => (
              <span key={i} className={cx('mr-1.5 rounded px-0.5', w.heard ? 'text-good' : 'bg-bad-soft text-bad underline decoration-wavy')}>{w.word}</span>
            ))}
          </p>
          <p className="mt-3 text-sm text-muted">We heard: “{s.transcript}”</p>
          <p className="mt-3 flex gap-1.5 text-xs text-muted"><Info className="mt-0.5 size-3.5 shrink-0" /> Red words were not recognised. This is a speech-recognition check of clarity, not a full pronunciation assessment: background noise and microphone quality affect it too.</p>
        </div>
      </div>
    )
  }
  const notes = s.feedback.notes
  const ai = s.aiFeedback
  return (
    <div className="space-y-4">
      <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
        {[
          ['Length', `${Math.round(m.durationS)} s`],
          ['Words', String(m.words)],
          ['Speed', `${m.articulationRate} wpm`],
          ['Long pauses', String(m.longPauses)],
        ].map(([k, v]) => (
          <div key={k} className="card p-3 text-center">
            <p className="text-xl font-extrabold tabular-nums">{v}</p>
            <p className="text-xs text-muted">{k}</p>
          </div>
        ))}
      </div>
      <div className="card p-5">
        <p className="text-sm font-bold text-muted">Transcript (automatic)</p>
        <p className="mt-1 text-[15.5px] leading-relaxed">{s.transcript}</p>
        <p className="mt-2 text-xs text-faint">Generated by speech recognition on our server. It may contain recognition mistakes. Your recording was not stored.</p>
      </div>
      {notes && (
        <div className="grid gap-3 md:grid-cols-3">
          {([['fluency', 'Fluency'], ['lexical', 'Vocabulary'], ['grammar', 'Grammar']] as const).map(([k, label]) => (
            <div key={k} className="card p-4">
              <p className="mb-2 font-bold">{label}</p>
              <Notes notes={notes[k]} />
            </div>
          ))}
        </div>
      )}
      {!!s.feedback.grammarIssues?.length && (
        <div className="card p-5">
          <p className="font-bold">Possible grammar issues</p>
          <ul className="mt-2 space-y-2 text-[15px]">
            {s.feedback.grammarIssues.map((g, i) => (
              <li key={i}>
                <span className="rounded bg-warn-soft px-1">{g.text}</span>
                {g.replacements.length > 0 && <> → <b>{g.replacements.join(' / ')}</b></>}
                <span className="block text-sm text-muted">{g.message}</span>
              </li>
            ))}
          </ul>
        </div>
      )}
      {ai ? (
        <div className="card border-primary/25 p-5">
          <div className="flex flex-wrap items-center gap-3">
            <p className="flex-1 font-bold">AI feedback <Badge>Unofficial estimate</Badge></p>
            <BandPill band={ai.fluency_band} label="Fluency" />
            <BandPill band={ai.lexical_band} label="Vocabulary" />
            <BandPill band={ai.grammar_band} label="Grammar" />
          </div>
          <p className="mt-3 text-[15px]">{ai.summary}</p>
          <div className="mt-4 grid gap-4 md:grid-cols-2">
            <div><p className="mb-1 text-sm font-bold text-good">Strengths</p><ul className="list-disc space-y-1 pl-5 text-[15px]">{ai.strengths.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
            <div><p className="mb-1 text-sm font-bold text-warn">To improve</p><ul className="list-disc space-y-1 pl-5 text-[15px]">{ai.improvements.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
          </div>
          {ai.better_phrases.length > 0 && (
            <div className="mt-4">
              <p className="mb-1 text-sm font-bold">Better ways to say it</p>
              <ul className="space-y-2 text-[15px]">
                {ai.better_phrases.map((b, i) => (
                  <li key={i} className="rounded-xl bg-surface-2 p-3"><s className="text-muted">{b.original}</s><br /><b>{b.better}</b><span className="block text-sm text-muted">{b.why}</span></li>
                ))}
              </ul>
            </div>
          )}
          <p className="mt-3 text-xs text-faint">Pronunciation isn’t scored: the AI only sees the transcript.</p>
        </div>
      ) : (
        allowAi && <AiFeedbackGate what="answer transcript" run={async () => onUpdate(await post<SpeakingSession>(`/speaking/${s.id}/ai-feedback`))}>Get estimated bands for fluency, vocabulary and grammar, plus better phrases. Only the transcript and timing are sent, never your voice.</AiFeedbackGate>
      )}
    </div>
  )
}
