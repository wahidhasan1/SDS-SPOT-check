import type { Dose, Exercise, ExerciseInstructions, Experience, IllustrationFrame } from '../domain/types';

/**
 * Centralized exercise library. Add new exercises here — the planner, library page,
 * substitution engine and coach all read from this list, so nothing else needs to change.
 *
 * Every exercise is equipment-free or uses ordinary household items (a wall, a sturdy
 * chair, a towel, a stair step). No purchase is ever required by the standard plan.
 *
 * Tags used by the planner:
 *   floor   – performed lying/kneeling on the floor
 *   supine  – lying on the back      prone – lying face down
 *   balance – single-leg balance demand
 *   warmup / cooldown / mobility – eligible for those blocks
 *   technique – good for technique-practice sessions
 */

const reps = (sets: number, lo: number, hi: number): Dose => ({ sets, reps: [lo, hi] });
const secs = (sets: number, s: number): Dose => ({ sets, seconds: s });
const levels = (b: Dose, i: Dose, a: Dose): Record<Experience, Dose> => ({ beginner: b, intermediate: i, advanced: a });
const f = (pose: string, label: string, props?: IllustrationFrame['props']): IllustrationFrame => ({ pose, label, props });

type Def = Omit<Exercise, 'cautions' | 'contraindications' | 'easier' | 'harder' | 'tags' | 'unilateral' | 'impact' | 'secondsPerRep' | 'restSec'> &
  Partial<Pick<Exercise, 'cautions' | 'contraindications' | 'easier' | 'harder' | 'tags' | 'unilateral' | 'impact' | 'secondsPerRep' | 'restSec'>>;

function ex(d: Def): Exercise {
  return {
    cautions: {},
    contraindications: [],
    easier: [],
    harder: [],
    tags: [],
    unilateral: false,
    impact: 'low',
    secondsPerRep: 3,
    restSec: 60,
    ...d,
  };
}

function ins(i: ExerciseInstructions): ExerciseInstructions {
  return i;
}

