export const PATH_LEVELS = ['beginner', 'intermediate', 'advanced'] as const;
export type PathLevel = (typeof PATH_LEVELS)[number];

export function cefrToPath(level: CefrLevel | null | undefined): PathLevel {
  if (!level || level === 'A1' || level === 'A2') return 'beginner';
  if (level === 'B1' || level === 'B2') return 'intermediate';
  return 'advanced';
}

export function cefrIndex(level: string | null | undefined): number {
  const i = CEFR_LEVELS.indexOf((level ?? '') as CefrLevel);
  return i;
}

